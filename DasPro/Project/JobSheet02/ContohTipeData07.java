public class ContohTipeData07 {
    public static void main(String[] args) {
        
        char golonganDarah = 'O';
        byte jarak = (byte) 100;
        short jumlahPendudukDalamSatuDusun = 1350;
        float suhu = 60.50F;
        double berat = 0.345678910;
        long saldo = 1375000000;
        int angkaDesimal = 0x10;

        System.out.println("Golongan darah saya adalah \t\t\t\t\t\t " + golonganDarah);
        System.out.println("Jarak rumah saya ke sekolah adalah \t\t\t\t\t " + jarak + " meter");
        System.out.println("Jumlah penduduk dalam satu dusun adalah \t\t\t " + jumlahPendudukDalamSatuDusun);
        System.out.println("Suhu ruangan adalah \t\t\t\t\t\t " + suhu + " derajat Celsius");
        System.out.println("Berat badan saya adalah \t\t\t\t\t " + berat + " kilogram");
        System.out.println("Saldo rekening saya adalah \t\t\t\t " + saldo);
        System.out.println("Angka desimal saya adalah \t\t\t\t\t " + angkaDesimal);
    }
}

        